async function main() {
  console.log(`Seeding ${products.length} products...`);
  for (const p of products) {
    await prisma.product.upsert({
      where: { slug: p.slug },
      update: p,
      create: p,
    });
  }

  // A handful of upcoming Saturday pickup dates, a few weeks out.
  const today = new Date();
  const pickupDates: Date[] = [];
  const d = new Date(today);
  d.setDate(d.getDate() + ((6 - d.getDay() + 7) % 7 || 7)); // next Saturday
  for (let i = 0; i < 6; i++) {
    pickupDates.push(new Date(d));
    d.setDate(d.getDate() + 7);
  }

  for (const date of pickupDates) {
    await prisma.pickupDate.upsert({
      where: { date },
      update: {},
      create: { date, capacity: 50, isOpen: true },
    });
  }

  console.log("Seed complete.");
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
